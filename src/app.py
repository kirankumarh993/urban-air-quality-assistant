"""Streamlit UI."""
import os
import sys

import streamlit as st

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from src import air_quality, engine, llm, validators  # noqa: E402

ICON = {0: "🟢", 1: "🟡", 2: "🟠", 3: "🔴", 4: "🟣", 5: "🟤"}
LABELS = {"healthy": "No special condition", "asthma_respiratory": "Asthma / respiratory condition",
          "heart_condition": "Heart condition", "child": "Child", "older_adult": "Older adult (65+)",
          "pregnant": "Pregnant"}
COMMUTE = {"walk": "Walk", "bicycle": "Bicycle", "public_transport": "Bus / metro / train", "car": "Car",
           "two_wheeler": "Motorbike / scooter", "work_from_home": "Work from home"}
ACT = {"walk": "Walk", "commute": "Commute", "run": "Run / intense exercise", "cycle": "Cycle",
       "outdoor_work": "Outdoor work", "ventilate_home": "Open windows at home"}


@st.cache_data(ttl=900, show_spinner=False)
def ai_plan(ctx_items: tuple):
    text = llm.plan(dict(ctx_items))
    if not text:
        raise RuntimeError(llm.last_error or "unknown error")  # exceptions are not cached
    return text


@st.cache_data(ttl=900, show_spinner=False)
def load(city: str):
    place = air_quality.geocode(city)
    return place, air_quality.fetch_air_quality(place["lat"], place["lon"])


def main() -> None:
    st.set_page_config(page_title="Urban Air Quality Assistant", page_icon="🌫️")
    st.title("Urban Air Quality Assistant")
    st.caption("Personalised, plain-language air advice. General guidance only, not medical advice.")
    with st.form("ctx"):
        city = st.text_input("City", "Delhi", max_chars=60, help="Type a city name")
        profile = st.selectbox("Health profile", list(LABELS), format_func=LABELS.get)
        activity = st.selectbox("Planned activity", list(ACT), format_func=ACT.get)
        minutes = st.number_input("Duration (minutes)", 5, 600, 45, step=5)
        commute = st.selectbox("Usual daily travel", list(COMMUTE), format_func=COMMUTE.get)
        purifier = st.checkbox("I have an air purifier at home")
        go = st.form_submit_button("Get advice")
    if not go:
        return
    try:
        city = validators.clean_city(city)
        profile = validators.clean_choice(profile, validators.PROFILES)
        activity = validators.clean_choice(activity, validators.ACTIVITIES)
        minutes = validators.clean_duration(minutes)
        commute = validators.clean_choice(commute, validators.COMMUTES)
        place, data = load(city)
    except (ValueError, air_quality.AirQualityError) as exc:
        st.error(str(exc))
        return
    a = engine.advise(data["aqi"], profile, activity, minutes, data["times"], data["hourly_aqi"])
    st.subheader(f"{place['name']}, {place['country']}")
    c1, c2, c3 = st.columns(3)
    c1.metric("US AQI", round(a.aqi))
    c2.metric("PM2.5 (µg/m³)", data["pm25"])
    c3.metric("PM10 (µg/m³)", data["pm10"])
    st.markdown(f"### {ICON[a.risk_level]} Decision: **{a.decision}** (air: {a.category}, your risk level {a.risk_level}/5)")
    for t in a.tips + [a.mask]:
        st.write("- " + t)
    if a.best_window:
        st.info(f"Cleanest hour in next 24 h: {a.best_window[0].replace('T', ' ')} (AQI about {a.best_window[1]})")
    base = engine.lifestyle_plan(a.risk_level, commute, bool(purifier))
    ctx = (("City", f"{place['name']}, {place['country']}"), ("US AQI", str(round(a.aqi))), ("Category", a.category),
           ("Decision (fixed)", a.decision), ("Health profile", LABELS[profile]), ("Planned activity", ACT[activity]),
           ("Usual travel", COMMUTE[commute]), ("Has air purifier", "yes" if purifier else "no"),
           ("Cleanest hour", a.best_window[0].replace("T", " ") if a.best_window else "unknown"))
    st.subheader("Your personalised low-emission plan")
    if not os.environ.get("GEMINI_API_KEY"):
        try:
            os.environ["GEMINI_API_KEY"] = str(st.secrets["GEMINI_API_KEY"])
        except Exception:  # no secrets configured
            pass
    err = ""
    with st.spinner("Preparing your plan..."):
        try:
            text = ai_plan(ctx)
        except RuntimeError as exc:
            text, err = None, str(exc)
    if text:
        st.caption("Generated by Gemini from the facts above. The decision itself comes from transparent rules.")
        st.markdown(text)
    else:
        st.caption("AI plan unavailable, showing the built-in rule-based plan.")
        if err:
            st.caption(f"Reason: {err}")
        st.markdown(f"**1. Low-emission routine for today**\n\n- {base['routine']}")
        st.markdown("**2. Indoor air hacks**\n\n" + "\n".join("- " + t for t in base["indoor"]))
        st.markdown(f"**3. Sustainable alternatives**\n\n- {base['alternative']}")
        st.markdown(f"**4. Impact of your choices**\n\n{base['impact']}")


if __name__ == "__main__":
    main()
